/* ============================================================================
   Reading-page behaviour
   ============================================================================
   GENERATED by course-engine/reading/apply.py from
   course-engine/reading/assets/reading.js. Do not edit in a site repo; edit it
   in the engine and re-apply.

   A standalone file rather than two more functions inside each site's
   assets/js/main.js: those have drifted apart across the family, and splicing
   into seven of them is exactly the hand-porting this engine exists to avoid.
   It is loaded only by reading pages, and does nothing if the page has no
   reading furniture on it.

   Everything here is an enhancement. With JavaScript off, the print button
   falls back to the browser's own Print command and the vocabulary tooltips
   stay centred on their word, which is how the CSS draws them anyway.
   ========================================================================= */
(function () {
  "use strict";

  /* ---------------------------------------------------------------
     Print / Save as PDF  ("[data-print-page]")
     ---------------------------------------------------------------
     A reading page IS the document, and this button turns it back into one.
     There is no A4 page-fitting to do -- a reading page is normal flowing
     content, so the print stylesheet does all the work and this only has to
     trigger the dialog.

     Waiting on document.fonts avoids printing a page whose webfonts have not
     loaded, which reflows the text in the saved PDF. */
  function initPagePrint() {
    var btns = document.querySelectorAll("[data-print-page]");
    if (!btns.length) return;
    Array.prototype.forEach.call(btns, function (btn) {
      btn.addEventListener("click", function () {
        var go = function () { window.print(); };
        if (document.fonts && document.fonts.ready) document.fonts.ready.then(go).catch(go);
        else go();
      });
    });
  }

  /* Vocabulary tooltips (.vocab-term::after, styled in assets/css/reading.css).
     The box is centred on its word, which sends it off the screen when the
     word sits near either edge -- common on a phone, where the passage is
     nearly as wide as the viewport. It is a pseudo-element, so it cannot be
     moved directly; instead its transform reads --vt-shift, which is set
     here. Nothing runs until the reader actually hovers or focuses a word. */
  function initVocabTooltips() {
    var terms = document.querySelectorAll(".vocab-term[data-definition]");
    if (!terms.length || !window.getComputedStyle) return;
    var PAD = 8;

    function place(term) {
      term.removeAttribute("data-vt-below");
      term.style.setProperty("--vt-shift", "0px");
      var box = window.getComputedStyle(term, "::after");
      var w = parseFloat(box.width);
      var h = parseFloat(box.height);
      if (!w) return;                       // no tooltip laid out; nothing to do
      var r = term.getBoundingClientRect();
      var centre = r.left + r.width / 2;
      var shift = 0;
      if (centre - w / 2 < PAD) shift = PAD - (centre - w / 2);
      else if (centre + w / 2 > window.innerWidth - PAD) {
        shift = (window.innerWidth - PAD) - (centre + w / 2);
      }
      if (shift) term.style.setProperty("--vt-shift", shift.toFixed(1) + "px");
      // Not enough room above -- open downwards instead.
      if (h && r.top - h < PAD + 12) term.setAttribute("data-vt-below", "");
    }

    Array.prototype.forEach.call(terms, function (t) {
      t.addEventListener("pointerenter", function () { place(t); });
      t.addEventListener("focus", function () { place(t); });
    });
  }

  function init() {
    initPagePrint();
    initVocabTooltips();
  }

  // The script is loaded at the end of the body, so the DOM may already be
  // parsed by the time it runs; DOMContentLoaded would never fire then.
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
